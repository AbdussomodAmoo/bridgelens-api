def attention_block(inputs):
    """Self-attention over the time dimension."""
    # inputs shape: (batch, timesteps, features)
    attention = Dense(1, activation='tanh')(inputs)          # (batch, timesteps, 1)
    attention = Flatten()(attention)                          # (batch, timesteps)
    attention = tf.keras.layers.Softmax()(attention)         # normalise
    attention = RepeatVector(inputs.shape[-1])(attention)    # (batch, features, timesteps)
    attention = Permute([2, 1])(attention)                   # (batch, timesteps, features)
    return Multiply()([inputs, attention])                   # weighted input

def build_model(input_shape, num_classes):
    inputs = Input(shape=input_shape)  # (30, 225)

    # Normalise inputs
    x = BatchNormalization()(inputs)

    # First Bidirectional LSTM
    x = Bidirectional(LSTM(
        128,
        return_sequences=True,
        dropout=0.3,
        recurrent_dropout=0.2,
        kernel_regularizer=l2(1e-4)
    ))(x)
    x = BatchNormalization()(x)

    # Attention
    x = attention_block(x)

    # Second Bidirectional LSTM
    x = Bidirectional(LSTM(
        64,
        return_sequences=True,
        dropout=0.3,
        recurrent_dropout=0.2,
        kernel_regularizer=l2(1e-4)
    ))(x)
    x = BatchNormalization()(x)

    # Global average pool over time
    x = GlobalAveragePooling1D()(x)

    # Dense head
    x = Dense(256, activation='relu', kernel_regularizer=l2(1e-4))(x)
    x = Dropout(0.5)(x)
    x = Dense(128, activation='relu', kernel_regularizer=l2(1e-4))(x)
    x = Dropout(0.3)(x)

    outputs = Dense(num_classes, activation='softmax')(x)

    return Model(inputs, outputs)

