def augment_sequence(X, y, noise_factor=0.01, scale_range=0.1):
    """
    Add noise and scale augmentation to increase effective dataset size.
    Critical for small datasets like this one.
    """
    X_aug, y_aug = [], []

    for seq, label in zip(X, y):
        # Original
        X_aug.append(seq)
        y_aug.append(label)

        # Gaussian noise
        noisy = seq + np.random.normal(0, noise_factor, seq.shape)
        X_aug.append(noisy)
        y_aug.append(label)

        # Random scale
        scale = 1.0 + np.random.uniform(-scale_range, scale_range)
        scaled = seq * scale
        X_aug.append(scaled)
        y_aug.append(label)

        # Time shift — roll frames slightly
        shift = np.random.randint(-3, 3)
        shifted = np.roll(seq, shift, axis=0)
        X_aug.append(shifted)
        y_aug.append(label)

    return np.array(X_aug, dtype=np.float32), np.array(y_aug)

