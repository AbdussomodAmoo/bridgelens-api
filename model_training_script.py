def extract_landmarks(frame_rgb, pose_det, hand_det):
    mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=frame_rgb)
    row = []

    pose_result = pose_det.detect(mp_image)
    if pose_result.pose_landmarks:
        for lm in pose_result.pose_landmarks[0]:
            row.extend([lm.x, lm.y, lm.z])
    else:
        row.extend([0.0] * 33 * 3)

    hand_result = hand_det.detect(mp_image)
    left  = [0.0] * 21 * 3
    right = [0.0] * 21 * 3

    if hand_result.hand_landmarks:
        for i, hand_lms in enumerate(hand_result.hand_landmarks):
            handedness = hand_result.handedness[i][0].category_name
            coords = [c for lm in hand_lms for c in [lm.x, lm.y, lm.z]]
            if handedness == 'Left':
                left = coords
            else:
                right = coords

    row.extend(left)
    row.extend(right)
    return row

def predict_sequence(sequence):
    arr   = np.array(sequence, dtype=np.float32)
    arr   = np.expand_dims(arr, axis=0)
    probs = model.predict(arr, verbose=0)[0]
    top3  = np.argsort(probs)[::-1][:3]
    return [
        {'label': le.inverse_transform([i])[0], 'confidence': float(probs[i])}
        for i in top3
    ]

def draw_results(frame, results, title="Prediction"):
    """Draw prediction results on frame and return as matplotlib figure."""
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    # Left — annotated frame
    frame_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB) if len(frame.shape) == 3 else frame
    axes[0].imshow(frame_rgb)
    axes[0].set_title(title, fontsize=14, fontweight='bold')
    axes[0].axis('off')

    # Right — confidence bar chart
    labels = [r['label'] for r in results]
    confs  = [r['confidence'] for r in results]
    colors = ['#00C851', '#FF8800', '#0099CC']

    bars = axes[1].barh(labels[::-1], confs[::-1], color=colors[::-1])
    axes[1].set_xlim(0, 1)
    axes[1].set_xlabel('Confidence', fontsize=12)
    axes[1].set_title('Top-3 Predictions', fontsize=14, fontweight='bold')

    for bar, conf in zip(bars, confs[::-1]):
        axes[1].text(
            bar.get_width() + 0.01,
            bar.get_y() + bar.get_height() / 2,
            f'{conf*100:.1f}%',
            va='center', fontsize=12, fontweight='bold'
        )

    # Big label overlay
    top_label = results[0]['label']
    top_conf  = results[0]['confidence']
    color     = 'green' if top_conf > CONFIDENCE_THRESH else 'orange'
