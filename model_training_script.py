STRIDE = 5  # predict every 5 new frames

buffer             = deque(maxlen=SEQUENCE_LENGTH)
prediction_history = deque(maxlen=5)
all_predictions    = []  # track predictions over time

with mp.tasks.vision.PoseLandmarker.create_from_options(pose_options) as pose_det, \
     mp.tasks.vision.HandLandmarker.create_from_options(hand_options) as hand_det:

    cap       = cv2.VideoCapture(f'/content/{filename}')
    frame_idx = 0

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        rgb           = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        landmarks     = extract_landmarks(rgb, pose_det, hand_det)
        hand_detected = any(v != 0.0 for v in landmarks[33*3:])

        if hand_detected:
            buffer.append(landmarks)

        if len(buffer) == SEQUENCE_LENGTH and frame_idx % STRIDE == 0:
            results = predict_sequence(list(buffer))
            top1    = results[0]
            prediction_history.append(top1['label'])

            # Majority vote
            counts         = Counter(prediction_history)
            stable_label   = counts.most_common(1)[0][0]
            stable_count   = counts.most_common(1)[0][1]

            all_predictions.append({
                'frame':      frame_idx,
                'top1':       top1['label'],
                'confidence': top1['confidence'],
                'stable':     stable_label,
                'agreed':     stable_count >= 3
            })

        frame_idx += 1
    cap.release()

# ── Results summary ───────────────────────────────────────────
print(f"\nProcessed {frame_idx} frames, made {len(all_predictions)} predictions\n")
print(f"{'Frame':<8} {'Raw Pred':<15} {'Conf':<8} {'Stable':<15} {'Agreed?'}")
